   private void searchbtnActionPerformed(java.awt.event.ActionEvent evt) {
    String key = search.getText().trim();

    if (key.isEmpty() || key.equalsIgnoreCase("Search by name")) {
        JOptionPane.showMessageDialog(this, "Enter craft name to search");
        return;
    }
    DefaultTableModel model = (DefaultTableModel) Dashboard_table.getModel();
    model.setRowCount(0); // clear table first
    //Exact search (Binary)
    Craft exact = craftController.searchByName(key);

    if (exact != null) {
        model.addRow(new Object[]{
            exact.getName(),
            exact.getCraftType(),
            exact.getPurpose()
        });
        return; 
    }
    //Partial search (Linear)
    List<Craft> results = craftController.searchPartialByName(key);

    if (results.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No matching crafts found");
        return;
    }
    int LIMIT = 50;
    int count = 0;

    for (Craft c : results) {
        model.addRow(new Object[]{
            c.getName(),
            c.getCraftType(),
            c.getPurpose()
        });

        count++;
        if (count >= LIMIT) break;
    }
}



