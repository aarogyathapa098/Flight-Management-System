    private void login_buttonMouseClicked(java.awt.event.MouseEvent evt) {// GEN-FIRST:event_login_buttonMouseClicked

        String username = Usernamefield_login.getText();
        String password = String.valueOf(PsField_login.getPassword());

        LoginController.LoginResult result =
                loginController.login(username, password);

        if (!result.success) {
            JOptionPane.showMessageDialog(this, result.error, "Login Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (result.admin) {
            isAdmin = true;
            applyDashboardPrivileges();

            name_txtfield.setText("admin");
            psfield_profile.setText(result.adminPassword);
            designation.setText("Admin");
            contact_txtfield.setText("9840262982");
        } else {
            isAdmin = false;
            applyDashboardPrivileges();

            User u = result.user;
            name_txtfield.setText(u.getUsername());
            psfield_profile.setText(u.getPassword());
            designation.setText(u.getDesignation());
            contact_txtfield.setText(u.getContact());
        }

        name_txtfield.setEditable(false);
        psfield_profile.setEditable(false);
        designation.setEditable(false);

        CardLayout card = (CardLayout) getContentPane().getLayout();
        card.show(getContentPane(), "dashboard");
        Main_Content.setVisible(true);
        aircraft_Panel.setVisible(false);
        Spacecraft_Panel.setVisible(false);
        Profile_Panel.setVisible(false);
        News_Panel.setVisible(false);
    }
