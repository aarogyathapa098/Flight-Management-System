    private void refreshHistoryUI() {
        List<String> added = craftController.getRecentAdded();
        List<String> deleted = craftController.getRecentDeleted();
        recentlyaddedtext.setText(listToHtml(added));
        recentlydeletedfield.setText(listToHtml(deleted));
        undo.setEnabled(craftController.canUndoDelete());
    }

    private String listToHtml(List<String> items) {
        StringBuilder sb = new StringBuilder("<html>");
        int limit = Math.min(3, items.size());
        for (int i = 0; i < limit; i++) {
            sb.append("• ").append(items.get(i)).append("<br>");
        }
        sb.append("</html>");
        return sb.toString();
    }

